#' write_doc_review.R — human-readable review of the bag edges the model reads.
#'
#' Writes data_products/01_entity_classification/DOC_BAGS_review.txt, rebuilt
#' from the pipeline's own products on every Stage 1 run (replaces the
#' hand-committed DOC_AUTHOR_BAGS_review.txt / doc_canonical_gsa_bags.csv
#' snapshots and 00_ingest/DOC_AUTHORS_review.txt, all deleted 2026-11-17). Three sections:
#'
#'   1. Coverage flags: crosswalk documents with no edge row, crosswalk
#'      authoring GSAs that never resolved in their document's text (so they
#'      author nothing in the model), edge rows with an empty profile, documents
#'      whose DWR-scraped gsa_names disagree with the roster names of their
#'      gsa_ids [SCRAPE-NAME MISMATCH], and authorship repaired from
#'      inputs/doc_author_overrides.csv [AUTHOR OVERRIDE].
#'   2. Plan family -> document -> authoring GSA bags (crosswalk gsa_ids), each
#'      marked with its alter count, or [NO EDGE ROW]. Also absorbs the old
#'      00_ingest/DOC_AUTHORS_review.txt (deleted 2026-11-17).
#'   3. Authoring bag -> its pooled corpus-wide alter profile, restricted to the
#'      alters the networks actually use: _entity_groups.R's entity_names()
#'      selection minus NON_ACTOR_ENTITIES, so this section changes whenever the
#'      model's grouping does. Shows alter counts per network (institutional,
#'      Consultant, Research, NGO), the count of excluded alters, and the top
#'      in-network alters by weight. Shown once per bag, since every edge row of
#'      a bag carries the same pooled profile.
#'
#' Reads:  00_ingest/id_crosswalk.csv, core sgma_gsa_full.csv (labels, if synced), gsa_bag_edges.csv, gsa_bag_edges_alters.csv,
#'         entity_bag_map.csv, inputs/entity_bag_overrides_gsa.csv
#' Writes: DOC_BAGS_review.txt
#' Run after build_gsa_bag_edges.R. No product the model reads.

suppressMessages(library(data.table))

.this_dir <- tryCatch(dirname(normalizePath(sys.frame(1)$ofile)), error = function(e) NA)
if (is.na(.this_dir)) {
  a <- commandArgs(FALSE); m <- grep("^--file=", a, value = TRUE)
  .this_dir <- if (length(m)) dirname(normalizePath(sub("^--file=", "", m[1]))) else
    "Network_Innovation_Paper/Code/01_entity_classification"
}
source(file.path(.this_dir, "..", "_paths.R"))
source(file.path(.this_dir, "..", "_entity_groups.R"))

TOP_N <- 15L
P <- function(f) nip_product("01_entity_classification", f)

e  <- fread(P("gsa_bag_edges.csv"), colClasses = list(character = c("gsp_doc_id", "plan_family_id")))
al <- fread(P("gsa_bag_edges_alters.csv"), na.strings = "")
cw <- fread(nip_product("00_ingest", "id_crosswalk.csv"),
            colClasses = list(character = c("gsp_doc_id", "gsp_id", "plan_family_id", "gsa_ids")))

# GSA bag labels: map label, else override canonical_label, else the id
mp <- fread(P("entity_bag_map.csv"))[grepl("^gsa_[0-9]+$", bag_id) & bag_label != bag_id,
                                      .(lab = bag_label[1]), by = bag_id]
ov <- fread(nip_input("entity_bag_overrides_gsa.csv"))[canonical_label != "",
                                                     .(lab2 = canonical_label[1]), by = bag_id]
ro <- if (file.exists(core_gsa_full()))
  unique(fread(core_gsa_full(), colClasses = "character")[, .(bag_id = paste0("gsa_", GSA_ID), lab3 = GSA_Name)], by = "bag_id") else
  data.table(bag_id = character(), lab3 = character())
gsa_lab <- function(b) {
  x <- mp[.(b), on = "bag_id", lab]; y <- ov[.(b), on = "bag_id", lab2]; z <- ro[.(b), on = "bag_id", lab3]
  fcoalesce(x, y, z, b)
}

# long authorship from the crosswalk
au <- cw[, .(gsa = paste0("gsa_", trimws(unlist(strsplit(gsa_ids, ","))))),
         by = .(gsp_doc_id, gsp_id, plan_family_id, submitted_date, doc_rank, gsa_ids_source)]
au <- au[gsa != "gsa_"]
au[, plan_family_id := sprintf("%04d", as.integer(plan_family_id))]

# per edge row: number of nonzero alters
acols <- setdiff(names(e), c("gsp_doc_id", "plan_family_id", "gsa", "gsa_label"))
mat <- as.matrix(e[, ..acols])
e[, n_alt := rowSums(mat > 0)]
au <- e[, .(gsp_doc_id, gsa, n_alt)][au, on = .(gsp_doc_id, gsa)]
au[, label := gsa_lab(gsa)]
au[, ovr := !is.na(gsa_ids_source) & gsa_ids_source == "override"]

# scraped gsa_names (";"-joined, non-parallel to gsa_ids) vs roster names, as sets
.nset <- function(x) sort(unique(trimws(unlist(strsplit(x, ";", fixed = TRUE)))))
mm <- if (nrow(ro)) {
  rn <- au[, .(roster = list(.nset(ro[.(gsa), on = "bag_id", lab3]))), by = gsp_doc_id]
  sc <- cw[, .(scraped = list(.nset(gsa_names))), by = gsp_doc_id]
  x <- sc[rn, on = "gsp_doc_id"]
  x[!mapply(identical, scraped, roster) & lengths(scraped) > 0, gsp_doc_id]
} else character()

out <- c(
  "# DOC_BAGS_review.txt — generated by Code/01_entity_classification/write_doc_review.R; do not edit.",
  sprintf("# Built %s from gsa_bag_edges.csv (%d rows, %d alter columns) and id_crosswalk.csv (%d docs).",
          format(Sys.time(), "%Y-%m-%d %H:%M"), nrow(e), length(acols), uniqueN(cw$gsp_doc_id)),
  "# Authorship = crosswalk gsa_ids. A crosswalk author whose name never resolves in its document's",
  "# text gets no edge row and is invisible to the model. Profiles are pooled corpus-wide per bag.")

# ---- 1. coverage flags
nodoc  <- setdiff(unique(cw$gsp_doc_id), unique(e$gsp_doc_id))
noedge <- au[is.na(n_alt)]
empty  <- e[n_alt == 0]
out <- c(out, "", "## 1. Coverage flags", "",
  sprintf("Documents with no edge row at all: %d", length(nodoc)),
  if (length(nodoc)) sprintf("    doc %6s  gsp %s", nodoc, cw[.(nodoc), on = "gsp_doc_id", gsp_id]),
  "",
  sprintf("Crosswalk authors with no edge row (unresolved in own text): %d of %d author slots", nrow(noedge), nrow(au)),
  if (nrow(noedge)) noedge[order(plan_family_id, doc_rank, gsa),
                           sprintf("    doc %6s  family %s  %-8s %s", gsp_doc_id, plan_family_id, gsa, label)],
  "",
  sprintf("Edge rows with an empty alter profile: %d", nrow(empty)),
  if (nrow(empty)) empty[, sprintf("    doc %6s  %-8s %s", gsp_doc_id, gsa, gsa_label)],
  "",
  if (nrow(ro)) sprintf("Documents whose scraped gsa_names disagree with the roster [SCRAPE-NAME MISMATCH]: %d", length(mm))
  else "Scrape-name check skipped: core sgma_gsa_full.csv not found.",
  if (length(mm)) unique(au[gsp_doc_id %in% mm][order(plan_family_id, doc_rank),
                     sprintf("    doc %6s  family %s  gsp %s", gsp_doc_id, plan_family_id, gsp_id)]),
  "",
  sprintf("Author slots repaired from inputs/doc_author_overrides.csv [AUTHOR OVERRIDE]: %d", sum(au$ovr)),
  if (any(au$ovr)) au[ovr == TRUE, sprintf("    doc %6s  family %s  %-8s %s", gsp_doc_id, plan_family_id, gsa, label)])

# ---- 2. family -> doc -> authors
out <- c(out, "", "## 2. Plan family -> document -> authoring GSA bags")
for (f in sort(unique(au$plan_family_id))) {
  d <- au[plan_family_id == f]
  out <- c(out, "", sprintf("### plan_family_id %s  (%d submission%s)", f, uniqueN(d$gsp_doc_id),
                            ifelse(uniqueN(d$gsp_doc_id) == 1, "", "s")))
  for (doc in unique(d[order(doc_rank)]$gsp_doc_id)) {
    r <- d[gsp_doc_id == doc][order(label)]
    out <- c(out, sprintf("  doc %6s  gsp %s  submitted %s  rank %s  (%d author%s, %d with edges)%s",
                          doc, r$gsp_id[1], r$submitted_date[1], r$doc_rank[1], nrow(r),
                          ifelse(nrow(r) == 1, "", "s"), sum(!is.na(r$n_alt)),
                          ifelse(doc %in% mm, " [SCRAPE-NAME MISMATCH]", "")),
             sprintf("       %-8s %-56s %s%s", r$gsa, r$label,
                     fifelse(is.na(r$n_alt), "[NO EDGE ROW]", sprintf("[%d alters]", r$n_alt)),
                     fifelse(r$ovr, " [AUTHOR OVERRIDE]", "")))
  }
}

# ---- 3. authoring bag -> pooled profile, in-network alters only
# owning type, exactly as entity_names() resolves it
al[, own := fifelse(!is.na(bag_type) & nzchar(bag_type), unname(BAG_TYPE_TO_ENTITY[bag_type]), entity_type)]
setkey(al, name)
NETS <- c("institutional", "Consultant", "Research", "NGO")
innet <- lapply(setNames(NETS, NETS), function(g) setdiff(entity_names(al, g), NON_ACTOR_ENTITIES))
bags <- unique(e, by = "gsa")[order(-n_alt, gsa_label)]
out <- c(out, "", sprintf("## 3. Authoring bag -> pooled alter profile (in-network alters; top %d by weight)", TOP_N),
         "# 'excluded' = Non_institutional, Institutional_unresolved and NON_ACTOR_ENTITIES alters,",
         "# which sit in gsa_bag_edges.csv but enter no network.")
for (i in seq_len(nrow(bags))) {
  w <- unlist(bags[i, ..acols]); w <- w[w > 0]
  nd <- uniqueN(e[gsa == bags$gsa[i], gsp_doc_id])
  k  <- vapply(innet, function(z) sum(names(w) %in% z), 0L)
  wi <- w[names(w) %in% innet$institutional]
  out <- c(out, "", sprintf("### %s  [%s]  (authors %d doc%s)", bags$gsa_label[i], bags$gsa[i],
                            nd, ifelse(nd == 1, "", "s")),
           sprintf("    alters: %s, excluded %d", paste(sprintf("%s %d", names(k), k), collapse = ", "),
                   length(w) - length(wi)))
  if (!length(wi)) next
  top <- head(order(-wi, names(wi)), TOP_N)
  nm  <- names(wi)[top]
  out <- c(out, sprintf("    %5g  %-19s %s", wi[top], al[.(nm), own], al[.(nm), bag_label]))
}

f <- P("DOC_BAGS_review.txt")
writeLines(out, f)
message(sprintf("wrote %s: %d docs, %d author slots (%d without edges), %d authoring bags",
                f, uniqueN(au$gsp_doc_id), nrow(au), nrow(noedge), nrow(bags)))
